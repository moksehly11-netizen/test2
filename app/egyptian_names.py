AMBIGUOUS_NAMES = {"نور", "بدر", "ملك", "وسام", "شمس", "ضياء", "يسرى", "يسري"}

# Common Egyptian name prefixes indicating female
FEMALE_PREFIXES = ("أم ", "ام ", "ست ")
# Common Egyptian name prefixes indicating male
MALE_PREFIXES = ("أبو ", "ابو ", "أبي ", "ابي ", "الشيخ ", "شيخ ", "دكتور ", "د.")


def _normalize(name: str) -> str:
    name = name.strip()
    # Normalize alef variants
    for ch in "أإآا":
        name = name.replace(ch, "ا")
    # Normalize ye variants
    name = name.replace("ى", "ي")
    # Normalize taa marbuta
    name = name.replace("ة", "ه")
    return name


def _first_word(name: str) -> str:
    return name.strip().split()[0] if name.strip() else ""


def predict_gender(full_name: str) -> str:
    """
    Returns 'female', 'male', or 'unknown'.
    Tries multiple strategies on Egyptian names.
    """
    if not full_name or not isinstance(full_name, str):
        return "unknown"

    name = full_name.strip()

    # Prefix check
    for p in FEMALE_PREFIXES:
        if name.startswith(p):
            return "female"
    for p in MALE_PREFIXES:
        if name.startswith(p):
            return "male"

    # Exact match (raw)
    if name in FEMALE_NAMES:
        return "female"
    if name in MALE_NAMES:
        return "male"

    # Normalized match
    norm = _normalize(name)
    norm_female = {_normalize(n) for n in FEMALE_NAMES}
    norm_male = {_normalize(n) for n in MALE_NAMES}

    if norm in norm_female:
        return "female"
    if norm in norm_male:
        return "male"

    # Try first word only
    first = _first_word(name)
    norm_first = _normalize(first)

    if first in FEMALE_NAMES or norm_first in norm_female:
        return "female"
    if first in MALE_NAMES or norm_first in norm_male:
        return "male"

    # Heuristic: Arabic female name endings
    if norm.endswith("ه") or norm.endswith("ا"):
        # Many female names end with ة/ا but not all
        # Only apply if no male match found
        pass

    return "unknown"
